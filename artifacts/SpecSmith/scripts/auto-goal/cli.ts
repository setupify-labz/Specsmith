#!/usr/bin/env tsx
// Auto Goal: one instruction in, a verified fix or an exact blocker out.
//
//   pnpm exec tsx scripts/auto-goal/cli.ts <command> --goal <id> [--issue <n>] [options]
//
// Commands (each loads the record, acts, saves it back with a revision check):
//   start            --goal <id> --request-file <f> --criteria-file <f> --branch <b> [--base main]
//                    --required-check <name> [...] (--issue <n> | --create-issue --title <t>)
//   resume           sync, then print the next action as JSON (what a check-in or a PR event runs)
//   sync             read the PR head, CI on that commit, and Codex verdicts into the record
//   next             print the next action as JSON
//   check            --criterion <id> --phase before|after   run that criterion's own command on HEAD
//   suite            --command <cmd>                        run a broader check on HEAD and record it
//   pr               --number <n>                           attach the draft PR (must be from the goal branch)
//   request-review   post "@codex review" on the PR for the current head and open a round
//   fixed            --finding <id>[,<id>] --commit <sha>   record which commit fixed which findings
//   fixed-ci         --commit <sha>                         record a commit made to fix red CI
//   dismiss          --finding <id> --reason <text>         record why a finding needs no change
//   finalize         record "complete" if, and only if, decide() says complete
//   block            --reason <text>                        record "blocked" with the exact reason
//   resolve-fork     --keep <comment id>                    continue from one copy of a revision two sessions both saved
//   status           print the record summary
//
// The record is an append-only log of comments on the goal's issue (--issue), mirrored to
// --store-dir (default .auto-goal/ at the repo root, git-ignored). Nothing here merges, schedules,
// publishes or calls a paid API.

import { spawn } from "node:child_process";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

import { decide } from "./decide.ts";
import { ghCli, type GitHub } from "./github.ts";
import { addEvent, createGoal, GoalError, type Criterion, type GoalRecord } from "./record.ts";
import { FileStore, IssueCommentStore, renderRecordComment, type GoalStore } from "./store.ts";
import { localGit, syncGoal, type Git } from "./sync.ts";

const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";

export interface Deps {
  github: GitHub;
  git: Git;
  /** Runs a shell command at the repo root; resolves to its exit code and the tail of its output. */
  exec(command: string): Promise<{ exitCode: number; tail: string }>;
  repoRoot: string;
  now(): Date;
  out(line: string): void;
}

function args(argv: readonly string[]) {
  const one = (name: string) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined; };
  const many = (name: string) => argv.flatMap((a, i) => (a === name && argv[i + 1] !== undefined ? [argv[i + 1]] : []));
  const need = (name: string) => { const v = one(name); if (v === undefined || v === "") throw new GoalError("invalid", `${name} is required.`); return v; };
  return { one, many, need, has: (name: string) => argv.includes(name) };
}

export function shellExec(cwd: string): Deps["exec"] {
  return (command) => new Promise((done) => {
    const child = spawn("bash", ["-c", command], { cwd, env: process.env });
    let buf = "";
    const keep = (chunk: Buffer) => { buf = (buf + chunk.toString("utf8")).slice(-20_000); };
    child.stdout.on("data", keep); child.stderr.on("data", keep);
    child.on("close", (code) => done({ exitCode: code ?? 1, tail: buf.replace(/\x1b\[[0-9;]*m/g, "").trim().split("\n").slice(-12).join("\n") }));
  });
}

async function headOfCleanTree(git: Git): Promise<string> {
  if (!(await git.isClean())) throw new GoalError("refused", "The working tree has uncommitted changes; a check must run on an exact commit. Commit or stash first.");
  return git.revParse("HEAD");
}

export async function main(argv: readonly string[], deps: Deps): Promise<number> {
  const [command] = argv;
  const a = args(argv.slice(1));
  const id = a.need("--goal");
  const mirror = new FileStore(resolve(deps.repoRoot, a.one("--store-dir") ?? ".auto-goal"));
  const issueArg = a.one("--issue");
  const now = deps.now();

  let trusted: string | null = null;
  const me = async () => (trusted ??= await deps.github.whoami());
  const storeFor = async (goal: Pick<GoalRecord, "repo" | "issue">): Promise<GoalStore> => goal.issue ? new IssueCommentStore(deps.github, goal.repo, goal.issue, await me(), mirror) : mirror;

  if (command === "start") {
    const request = (await readFile(resolve(a.need("--request-file")), "utf8")).trim();
    const criteria = JSON.parse(await readFile(resolve(a.need("--criteria-file")), "utf8")) as Criterion[];
    let goal = createGoal({ id, request, acceptanceCriteria: criteria, repo: a.one("--repo") ?? "setupify-labz/Specsmith", baseBranch: a.one("--base") ?? "main", branch: a.need("--branch"), requiredChecks: a.many("--required-check"), now });
    if (!issueArg && !a.has("--create-issue")) throw new GoalError("invalid", "start needs --issue <n> or --create-issue: the record must live on GitHub to survive the container (.auto-goal/ is only a local mirror).");
    if (issueArg) goal.issue = Number(issueArg);
    else {
      const body = [
        `**Auto Goal \`${id}\`.** The request, as given:`, "", request.split("\n").map((l) => `> ${l}`).join("\n"), "",
        "**Acceptance criteria** (each check must fail before the fix and pass after it):", "",
        ...criteria.map((c) => `- **${c.id}** (${c.kind}): ${c.text}\n  Check: \`${c.command}\``), "",
        `Complete only when every check passes on the final commit, CI (${goal.requiredChecks.join(", ")}) is green on that commit, and Codex's material findings are resolved.`,
        `Caps: ${goal.caps.maxReviewRounds} review rounds, ${goal.caps.maxFixAttempts} fix attempts, ${goal.caps.maxHours} h, $0 paid spend. Merging, paid generation, scheduling and publishing are off.`,
        "", "The goal's durable record is the marked comment below; the orchestrator edits it in place.",
      ].join("\n");
      const issue = await deps.github.createIssue(goal.repo, a.need("--title"), body + FOOTER);
      goal.issue = issue.number;
      addEvent(goal, "issue", `Opened ${issue.html_url} to hold the record.`, now);
    }
    goal = await (await storeFor(goal)).save(goal, now);
    deps.out(JSON.stringify({ goal: id, issue: goal.issue, revision: goal.revision, next: decide(goal, now) }, null, 2));
    return 0;
  }

  // Every other command works on the stored record.
  const local = await mirror.load(id).catch(() => null);
  const issue = issueArg ? Number(issueArg) : local?.issue ?? null;
  const repo = a.one("--repo") ?? local?.repo ?? "setupify-labz/Specsmith";
  // Recovery from a fork must run before the (refusing) load below.
  if (command === "resolve-fork") {
    if (!issue) throw new GoalError("invalid", "resolve-fork needs the goal issue (--issue).");
    const kept = await new IssueCommentStore(deps.github, repo, issue, await me(), mirror).resolveFork(id, Number(a.need("--keep")), now);
    deps.out(`Continuing from revision ${kept.revision}.`);
    return 0;
  }
  const store = issue ? new IssueCommentStore(deps.github, repo, issue, await me(), mirror) : mirror;
  let goal = await store.load(id);
  const save = async () => { goal = await store.save(goal, now); };
  const refuseIfDone = () => { if (goal.outcome) throw new GoalError("refused", `Goal ${id} is already ${goal.outcome.status}: ${goal.outcome.reason}`); };

  switch (command) {
    case "status": {
      deps.out(renderRecordComment(goal, now).split("<details>")[0].trim());
      return 0;
    }
    case "next": {
      const next = decide(goal, now);
      if (goal.step !== next.action && !goal.outcome) { goal.step = next.action; addEvent(goal, "step", `${next.action}: ${next.why}`, now); await save(); }
      deps.out(JSON.stringify(next, null, 2));
      return 0;
    }
    case "sync":
    case "resume": {
      refuseIfDone();
      await syncGoal(goal, deps.github, deps.git, now);
      const next = decide(goal, now);
      if (goal.step !== next.action && !goal.outcome) { goal.step = next.action; addEvent(goal, "step", `${next.action}: ${next.why}`, now); }
      // A genuine blocker (a cap, a timeout, Codex unable to review) ends the goal with its exact reason.
      if (next.action === "blocked" && !goal.outcome) {
        goal.outcome = { status: "blocked", at: now.toISOString(), reason: next.why, evidence: { head: goal.head, pr: goal.pr, rounds: goal.reviewRounds.map((r) => ({ n: r.n, verdict: r.verdict, evidence: r.evidence })) } };
        addEvent(goal, "blocked", next.why, now);
      }
      await save();
      deps.out(JSON.stringify(command === "resume" ? next : { head: goal.head, ci: goal.ci?.runs.map((r) => `${r.name}: ${r.conclusion ?? r.status}`), rounds: goal.reviewRounds.map((r) => `${r.n} ${r.verdict}`), next }, null, 2));
      return 0;
    }
    case "check": {
      refuseIfDone();
      const criterion = goal.acceptanceCriteria.find((c) => c.id === a.need("--criterion"));
      if (!criterion) throw new GoalError("invalid", `Goal ${id} has no criterion ${a.one("--criterion")}.`);
      const phase = a.need("--phase");
      if (phase !== "before" && phase !== "after") throw new GoalError("invalid", "--phase must be before or after.");
      const sha = await headOfCleanTree(deps.git);
      const result = await deps.exec(criterion.command);
      goal.checks.push({ criterionId: criterion.id, phase, command: criterion.command, sha, exitCode: result.exitCode, summary: result.tail, at: now.toISOString() });
      const expected = phase === "before" ? result.exitCode !== 0 : result.exitCode === 0;
      addEvent(goal, `check-${phase}`, `${criterion.id} on ${sha.slice(0, 10)}: exit ${result.exitCode}${expected ? "" : phase === "before" ? " (did NOT fail: the check does not detect the defect)" : " (still failing)"}.`, now);
      await save();
      deps.out(`${criterion.id} ${phase} on ${sha.slice(0, 10)}: exit ${result.exitCode}\n${result.tail}`);
      return expected ? 0 : 1;
    }
    case "suite": {
      refuseIfDone();
      const cmd = a.need("--command");
      const sha = await headOfCleanTree(deps.git);
      const result = await deps.exec(cmd);
      goal.checks.push({ criterionId: null, phase: "suite", command: cmd, sha, exitCode: result.exitCode, summary: result.tail, at: now.toISOString() });
      addEvent(goal, "suite", `\`${cmd}\` on ${sha.slice(0, 10)}: exit ${result.exitCode}.`, now);
      await save();
      deps.out(`exit ${result.exitCode}\n${result.tail}`);
      return result.exitCode === 0 ? 0 : 1;
    }
    case "pr": {
      refuseIfDone();
      const n = Number(a.need("--number"));
      const pull = await deps.github.pull(goal.repo, n);
      if (pull.head.ref !== goal.branch) throw new GoalError("invalid", `PR #${n} is from ${pull.head.ref}, not ${goal.branch}.`);
      goal.pr = n;
      addEvent(goal, "pr", `Attached ${pull.html_url} (draft: ${pull.draft}).`, now);
      await syncGoal(goal, deps.github, deps.git, now);
      await save();
      deps.out(JSON.stringify(decide(goal, now), null, 2));
      return 0;
    }
    case "request-review": {
      refuseIfDone();
      await syncGoal(goal, deps.github, deps.git, now);
      const next = decide(goal, now);
      if (next.action !== "request-review") throw new GoalError("refused", `Not requesting a review: next action is ${next.action} (${next.why}).`);
      // Two phases, so a crash between them cannot trigger Codex without a record of it:
      // 1. save the round as in flight (no request URL yet); 2. post, or adopt a request already
      // posted for this round, and save its URL. A resumed session re-enters at phase 2.
      let round = goal.reviewRounds.at(-1);
      if (!round || round.requestUrl !== null || round.requestedSha !== goal.head) {
        round = { n: goal.reviewRounds.length + 1, requestedAt: now.toISOString(), requestedSha: goal.head!, requestUrl: null, verdict: "pending", reviewedSha: null, completedAt: null, evidence: null };
        goal.reviewRounds.push(round);
        goal.step = "request-review";
        addEvent(goal, "review-opening", `Round ${round.n} on ${round.requestedSha.slice(0, 10)}: saved before asking Codex.`, now);
        await save();
        round = goal.reviewRounds.at(-1)!;
      }
      const tag = `Auto Goal \`${id}\`, review round ${round.n} of at most ${goal.caps.maxReviewRounds}, for \`${round.requestedSha}\`.`;
      const self = await me();
      const already = (await deps.github.issueComments(goal.repo, goal.pr!)).find((c) => c.user.login === self && c.body.startsWith("@codex review") && c.body.includes(tag));
      const note = a.one("--note");
      const comment = already ?? await deps.github.createComment(goal.repo, goal.pr!, `@codex review\n\n${tag}${note ? `\n\n${note}` : ""}${FOOTER}`);
      round.requestUrl = comment.html_url;
      round.requestedAt = comment.created_at;
      goal.step = "wait-review";
      addEvent(goal, "review-requested", `Round ${round.n} on ${round.requestedSha.slice(0, 10)}: ${comment.html_url}${already ? " (found already posted; not posted again)" : ""}`, now);
      await save();
      deps.out(comment.html_url);
      return 0;
    }
    case "fixed":
    case "fixed-ci": {
      refuseIfDone();
      await syncGoal(goal, deps.github, deps.git, now);
      const sha = await deps.git.revParse(a.need("--commit"));
      if (!goal.commits.some((c) => c.sha === sha)) throw new GoalError("refused", `${sha.slice(0, 10)} is not on the goal branch's head (${goal.head?.slice(0, 10)}); push it first.`);
      if (command === "fixed") {
        const ids = a.need("--finding").split(",");
        for (const fid of ids) {
          const f = goal.findings.find((x) => x.id === fid);
          if (!f) throw new GoalError("invalid", `No finding ${fid}.`);
          const round = goal.reviewRounds.find((r) => r.n === f.round)!;
          if (sha === round.requestedSha || !goal.commits.slice(goal.commits.findIndex((c) => c.sha === round.requestedSha) + 1).some((c) => c.sha === sha)) {
            throw new GoalError("refused", `${sha.slice(0, 10)} is not a commit after the one Codex reviewed in round ${f.round}; it cannot have fixed finding ${fid}.`);
          }
          f.status = "fixed"; f.fixedIn = sha;
        }
        addEvent(goal, "fixed", `${ids.join(", ")} fixed in ${sha.slice(0, 10)}.`, now);
      } else addEvent(goal, "fixed-ci", `CI fix in ${sha.slice(0, 10)}.`, now);
      if (!goal.fixCommits.includes(sha)) { goal.fixCommits.push(sha); goal.fixAttempts = goal.fixCommits.length; }
      await save();
      deps.out(JSON.stringify(decide(goal, now), null, 2));
      return 0;
    }
    case "dismiss": {
      refuseIfDone();
      const f = goal.findings.find((x) => x.id === a.need("--finding"));
      if (!f) throw new GoalError("invalid", `No finding ${a.one("--finding")}.`);
      f.status = "dismissed"; f.reason = a.need("--reason");
      addEvent(goal, "dismissed", `${f.id} (${f.priority} ${f.title}): ${f.reason}`, now);
      await save();
      deps.out(JSON.stringify(decide(goal, now), null, 2));
      return 0;
    }
    case "finalize": {
      refuseIfDone();
      await syncGoal(goal, deps.github, deps.git, now);
      const next = decide(goal, now);
      if (next.action !== "complete") { await save(); throw new GoalError("refused", `Not complete: next action is ${next.action} (${next.why}).`); }
      const head = goal.head!;
      goal.outcome = {
        status: "complete", at: now.toISOString(), reason: next.why,
        evidence: {
          head, pr: goal.pr, issue: goal.issue,
          acceptance: goal.acceptanceCriteria.map((c) => ({ id: c.id, before: goal.checks.find((r) => r.criterionId === c.id && r.phase === "before" && r.exitCode !== 0)?.sha, after: head })),
          ci: goal.ci!.runs.map((r) => ({ name: r.name, conclusion: r.conclusion, url: r.url })),
          review: goal.reviewRounds.at(-1)!.evidence,
          findings: goal.findings.map((f) => ({ id: f.id, priority: f.priority, status: f.status, fixedIn: f.fixedIn, reason: f.reason })),
        },
      };
      goal.step = "complete";
      addEvent(goal, "complete", next.why, now);
      await save();
      deps.out(JSON.stringify(goal.outcome, null, 2));
      return 0;
    }
    case "block": {
      refuseIfDone();
      goal.outcome = { status: "blocked", at: now.toISOString(), reason: a.need("--reason"), evidence: { head: goal.head, pr: goal.pr } };
      goal.step = "blocked";
      addEvent(goal, "blocked", goal.outcome.reason, now);
      await save();
      deps.out(goal.outcome.reason);
      return 0;
    }
    default:
      throw new GoalError("invalid", `Unknown command "${command}".`);
  }
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  const repoRoot = (await import("node:child_process")).execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
  const deps: Deps = { github: ghCli, git: localGit(repoRoot), exec: shellExec(repoRoot), repoRoot, now: () => new Date(), out: (l) => console.log(l) };
  try {
    process.exitCode = await main(process.argv.slice(2), deps);
  } catch (error) {
    if (error instanceof GoalError) { console.error(`${error.code.toUpperCase()}: ${error.message}`); process.exitCode = error.code === "unavailable" ? 3 : 2; }
    else throw error;
  }
}
