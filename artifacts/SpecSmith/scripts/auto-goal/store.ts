// Where a goal record lives.
//
// The durable copy is an append-only log of comments on the goal's GitHub issue: every save posts
// a new comment carrying the next revision, and no comment is ever edited. It survives the
// container, needs no branch (so it triggers no CI or preview build), and keeps every revision.
//
// GitHub offers no compare-and-swap for comments, so two sessions saving from the same revision
// cannot be stopped from both posting. Append-only makes that visible instead of lossy: both
// copies stay, the writer that finds a rival comment at its revision fails, and every later load
// refuses the fork until `resolve-fork` records which copy to keep. Nothing is silently dropped.
// Only comments by the orchestrator's own login count as records (anyone else who can comment on
// the issue could otherwise post a "higher revision" with a different check command), and the
// request and acceptance criteria are pinned to revision 1: no later revision may change them.
// A local file mirrors the latest revision for offline reads and tests.

import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

import type { GitHub } from "./github.ts";
import { GoalError, validateGoal, type GoalRecord } from "./record.ts";
import { decide } from "./decide.ts";

export interface GoalStore {
  load(id: string): Promise<GoalRecord>;
  /** Writes `goal` as revision `goal.revision + 1` if the stored revision is still `goal.revision`. Returns the saved record. */
  save(goal: GoalRecord, now?: Date): Promise<GoalRecord>;
}

const bump = (goal: GoalRecord, now: Date): GoalRecord => validateGoal({ ...structuredClone(goal), revision: goal.revision + 1, updatedAt: now.toISOString() });

export class FileStore implements GoalStore {
  constructor(readonly dir: string) {}
  path(id: string) { return join(this.dir, `${id}.json`); }
  async load(id: string): Promise<GoalRecord> {
    let text: string;
    try { text = await readFile(this.path(id), "utf8"); } catch { throw new GoalError("not-found", `No goal record at ${this.path(id)}.`); }
    return validateGoal(JSON.parse(text));
  }
  async exists(id: string): Promise<boolean> { return this.load(id).then(() => true, () => false); }
  async save(goal: GoalRecord, now = new Date()): Promise<GoalRecord> {
    const stored = await this.load(goal.id).catch((e: GoalError) => { if (e.code === "not-found") return null; throw e; });
    const expected = stored?.revision ?? 0;
    if (goal.revision !== expected) throw new GoalError("conflict", `Goal ${goal.id} changed underneath this update (stored revision ${expected}, update based on ${goal.revision}). Reload and retry.`);
    const next = bump(goal, now);
    await mkdir(dirname(this.path(goal.id)), { recursive: true });
    const tmp = `${this.path(goal.id)}.${process.pid}.${Date.now()}.tmp`;
    await writeFile(tmp, `${JSON.stringify(next, null, 2)}\n`);
    await rename(tmp, this.path(goal.id));
    return next;
  }
  /** Replaces the local mirror with a copy read from the durable store (no revision check: the durable copy wins). */
  async mirror(goal: GoalRecord): Promise<void> {
    await mkdir(this.dir, { recursive: true });
    const tmp = `${this.path(goal.id)}.${process.pid}.${Date.now()}.tmp`;
    await writeFile(tmp, `${JSON.stringify(goal, null, 2)}\n`);
    await rename(tmp, this.path(goal.id));
  }
}

const MARKER = (id: string, revision: number) => `<!-- specsmith-auto-goal id=${id} rev=${revision} -->`;
const MARKER_RE = /^<!-- specsmith-auto-goal id=([a-z0-9-]+)(?: rev=(\d+))? -->/;
const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
const COMMENT_LIMIT = 65_000;

/** The comment body: a short human summary, then the record as JSON. */
export function renderRecordComment(goal: GoalRecord, now = new Date()): string {
  const next = decide(goal, now);
  const lines = [
    MARKER(goal.id, goal.revision),
    `**Auto Goal record \`${goal.id}\`** (revision ${goal.revision}, updated ${goal.updatedAt})`,
    "",
    `- Outcome: ${goal.outcome ? `**${goal.outcome.status}**: ${goal.outcome.reason}` : "in progress"}`,
    `- Next step: \`${next.action}\`: ${next.why}`,
    `- PR: ${goal.pr ? `#${goal.pr}` : "not opened yet"}; head: ${goal.head ? `\`${goal.head.slice(0, 10)}\`` : "none"}`,
    `- Review rounds: ${goal.reviewRounds.length}/${goal.caps.maxReviewRounds}; fix attempts: ${goal.fixAttempts}/${goal.caps.maxFixAttempts}; paid spend allowed: $0`,
    `- Findings: ${goal.findings.length ? goal.findings.map((f) => `${f.priority} ${f.status}: ${f.title}`).join("; ") : "none"}`,
    "",
    "This comment is one revision of the goal's durable record. Each save adds a new comment; the highest revision is current.",
    "",
  ];
  const json = (space?: number) => ["<details><summary>Record (JSON)</summary>", "", "```json", JSON.stringify(goal, null, space), "```", "", "</details>"].join("\n");
  let body = `${lines.join("\n")}${json(1)}${FOOTER}`;
  if (body.length > COMMENT_LIMIT) body = `${lines.join("\n")}${json()}${FOOTER}`;
  if (body.length > COMMENT_LIMIT) throw new GoalError("refused", `Goal ${goal.id}'s record is ${body.length} characters, over GitHub's comment limit; trim its events before saving.`);
  return body;
}

export function parseRecordComment(body: string, id: string): GoalRecord | null {
  const marker = MARKER_RE.exec(body);
  if (!marker || marker[1] !== id) return null;
  const m = /```json\n([\s\S]*?)\n```/.exec(body);
  if (!m) throw new GoalError("invalid", `Goal ${id}'s record comment has no JSON block.`);
  const goal = validateGoal(JSON.parse(m[1]));
  if (marker[2] !== undefined && Number(marker[2]) !== goal.revision) throw new GoalError("invalid", `Goal ${id}'s record comment says revision ${marker[2]} but holds revision ${goal.revision}.`);
  return goal;
}

interface Entry { readonly commentId: number; readonly url: string; readonly goal: GoalRecord }

export class IssueCommentStore implements GoalStore {
  /** `trustedLogin`: the GitHub login the orchestrator posts as (GitHub.whoami()). */
  constructor(readonly github: GitHub, readonly repo: string, readonly issue: number, readonly trustedLogin: string, readonly mirrorTo?: FileStore) {}

  /** Every revision of the goal saved by the trusted login, in posting order. Anyone else's marked comment is ignored. */
  private async entries(id: string): Promise<Entry[]> {
    const comments = await this.github.issueComments(this.repo, this.issue);
    const out: Entry[] = [];
    for (const c of comments) {
      if (c.user.login !== this.trustedLogin) continue;
      const goal = parseRecordComment(c.body, id);
      if (goal) out.push({ commentId: c.id, url: c.html_url, goal });
    }
    const first = out.find((e) => e.goal.revision === Math.min(...out.map((x) => x.goal.revision)));
    const pinned = first && JSON.stringify([first.goal.request, first.goal.acceptanceCriteria, first.goal.repo, first.goal.branch]);
    for (const e of out) {
      if (JSON.stringify([e.goal.request, e.goal.acceptanceCriteria, e.goal.repo, e.goal.branch]) !== pinned) {
        throw new GoalError("invalid", `Goal ${id}'s record ${e.url} changes the request, acceptance criteria, repo or branch fixed at revision ${first!.goal.revision}; refusing it.`);
      }
    }
    return out;
  }

  /** Revisions saved more than once, other than forks the latest record has already resolved. */
  private static forks(entries: readonly Entry[], latest: GoalRecord): Map<number, Entry[]> {
    const byRev = new Map<number, Entry[]>();
    for (const e of entries) byRev.set(e.goal.revision, [...(byRev.get(e.goal.revision) ?? []), e]);
    const resolved = new Set(latest.resolvedForks ?? []);
    return new Map([...byRev].filter(([rev, list]) => list.length > 1 && !resolved.has(rev)));
  }

  private current(id: string, entries: readonly Entry[]): Entry {
    if (entries.length === 0) throw new GoalError("not-found", `No record for goal ${id} on ${this.repo}#${this.issue}.`);
    const top = Math.max(...entries.map((e) => e.goal.revision));
    const atTop = entries.filter((e) => e.goal.revision === top);
    const latest = atTop[atTop.length - 1];
    const forks = IssueCommentStore.forks(entries, latest.goal);
    if (forks.size) {
      const list = [...forks].map(([rev, es]) => `revision ${rev}: ${es.map((e) => e.url).join(", ")}`).join("; ");
      throw new GoalError("conflict", `Goal ${id} has diverging saves (${list}). Nothing was dropped; choose the copy to keep with resolve-fork --keep <comment id>.`);
    }
    return latest;
  }

  async load(id: string): Promise<GoalRecord> {
    const goal = this.current(id, await this.entries(id)).goal;
    await this.mirrorTo?.mirror(goal);
    return goal;
  }

  async save(goal: GoalRecord, now = new Date()): Promise<GoalRecord> {
    const before = await this.entries(goal.id);
    const stored = before.length ? this.current(goal.id, before) : null;
    const expected = stored?.goal.revision ?? 0;
    if (goal.revision !== expected) throw new GoalError("conflict", `Goal ${goal.id} changed on GitHub (stored revision ${expected}, update based on ${goal.revision}). Reload and retry.`);
    const next = bump({ ...goal, parentComment: stored?.commentId ?? null }, now);
    const posted = await this.github.createComment(this.repo, this.issue, renderRecordComment(next, now));
    // No compare-and-swap exists for comments, so check afterwards: a rival at this revision means
    // two sessions saved from the same base. Both copies stay; this writer reports the fork.
    // Only another entry at this same revision is a rival; a later revision built on this one is a normal successor.
    const rivals = (await this.entries(goal.id)).filter((e) => e.goal.revision === next.revision && e.commentId !== posted.id);
    if (rivals.length) throw new GoalError("conflict", `Another session saved goal ${goal.id} at the same time (${rivals.map((e) => e.url).join(", ")}; this save: ${posted.html_url}). Both are kept; choose one with resolve-fork --keep <comment id>.`);
    await this.mirrorTo?.mirror(next);
    return next;
  }

  /**
   * Continues from the chosen copy of a forked revision, recording the fork as resolved. Work saved
   * on top of the chosen copy (its descendants, by parent comment) is kept: the goal continues from
   * the newest of them. If that lineage branches again, or a later revision's parent is unknown,
   * the choice is ambiguous and is refused rather than guessed.
   */
  async resolveFork(id: string, keepCommentId: number, now = new Date()): Promise<GoalRecord> {
    const entries = await this.entries(id);
    const kept = entries.find((e) => e.commentId === keepCommentId);
    if (!kept) throw new GoalError("not-found", `Comment ${keepCommentId} is not a record of goal ${id} on #${this.issue}.`);
    const top = Math.max(...entries.map((e) => e.goal.revision));
    const forked = [...new Set(entries.map((e) => e.goal.revision).filter((rev, i, all) => all.indexOf(rev) !== i))];
    if (!forked.includes(kept.goal.revision)) throw new GoalError("refused", `Comment ${keepCommentId} is not one of the diverging copies (forked revisions: ${forked.join(", ") || "none"}).`);
    const later = entries.filter((e) => e.goal.revision > kept.goal.revision);
    const unknown = later.filter((e) => e.goal.parentComment === undefined || e.goal.parentComment === null);
    if (unknown.length) throw new GoalError("refused", `Cannot tell which later saves descend from ${kept.url}: ${unknown.map((e) => e.url).join(", ")} record no parent. Resolve by hand.`);
    const lineage = new Set([kept.commentId]);
    for (const e of [...later].sort((a, b) => a.goal.revision - b.goal.revision)) if (lineage.has(e.goal.parentComment!)) lineage.add(e.commentId);
    const line = entries.filter((e) => lineage.has(e.commentId));
    const tipRev = Math.max(...line.map((e) => e.goal.revision));
    const tips = line.filter((e) => e.goal.revision === tipRev);
    if (tips.length > 1) throw new GoalError("refused", `The saves built on ${kept.url} branch again at revision ${tipRev} (${tips.map((e) => e.url).join(", ")}); keep one of those instead.`);
    const tip = tips[0];
    const goal = structuredClone(tip.goal);
    goal.resolvedForks = [...new Set([...(goal.resolvedForks ?? []), ...forked])].sort((a, b) => a - b);
    goal.events.push({ at: now.toISOString(), type: "fork-resolved", detail: `Kept ${kept.url} (revision ${kept.goal.revision})${tip === kept ? "" : ` and its descendants up to ${tip.url} (revision ${tipRev})`}; the other copies stay on the issue, unused.` });
    const next = bump({ ...goal, revision: top, parentComment: tip.commentId }, now);
    await this.github.createComment(this.repo, this.issue, renderRecordComment(next, now));
    await this.mirrorTo?.mirror(next);
    return next;
  }
}
